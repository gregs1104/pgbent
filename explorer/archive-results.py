#!/usr/bin/env python3
"""
Published results snapshots — export Streamlit studies to Markdown on getbent.io.

Usage:
  python3 explorer/archive-results.py --pg 18
  python3 explorer/archive-results.py --pg 18 --study osm-power
  python3 explorer/archive-results.py --list-studies

Writes under docs/results-summary/pg<major>/ by default. Each export documents
what the live Streamlit app showed at snapshot time; Streamlit stays the live
path for the next release (e.g. PG 19).
"""

from __future__ import annotations

import argparse
import os
import sys
from datetime import date

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import pandas as pd
import psycopg2

from submission_studies import STUDIES, study_sql

DEFAULT_CONN = "host='localhost' dbname='results' user='gsmith' password='secret'"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Archive submission studies as Markdown")
    parser.add_argument("--pg", metavar="MAJOR", help="PostgreSQL major version filter (e.g. 18)")
    parser.add_argument("--study", default="all", help="Study id or 'all' (default: all)")
    parser.add_argument(
        "--output",
        help="Output directory (default: docs/results-summary/pg<MAJOR> or docs/results-summary)",
    )
    parser.add_argument("--conn", default=os.environ.get("RESULTS_CONN", DEFAULT_CONN))
    parser.add_argument("--list-studies", action="store_true", help="List study ids and exit")
    return parser.parse_args()


def connect(conn_string: str):
    print(f"Connecting to results database")
    return psycopg2.connect(conn_string)


def dataframe_to_markdown(df: pd.DataFrame) -> str:
    if df.empty:
        return "_No rows._"
    cols = [str(c) for c in df.columns]
    lines = [
        "| " + " | ".join(cols) + " |",
        "| " + " | ".join("---" for _ in cols) + " |",
    ]
    for _, row in df.iterrows():
        cells = []
        for val in row:
            if val is None or (isinstance(val, float) and pd.isna(val)):
                cells.append("")
            else:
                cells.append(str(val).replace("|", "\\|"))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def study_frontmatter(study_id: str, pg_major: str | None, nav_order: int) -> str:
    meta = STUDIES[study_id]
    slug = study_id
    if pg_major:
        permalink = f"/results-summary/pg{pg_major}/{slug}/"
        parent = f"PostgreSQL {pg_major}"
    else:
        permalink = f"/results-summary/{slug}/"
        parent = "Results summary"
    return f"""---
layout: home
title: {meta['title']}
permalink: {permalink}
parent: {parent}
nav_order: {nav_order}
---

# {meta['title']}

{meta['description']}

_Snapshot of the [Streamlit results explorer](https://pgbent.streamlit.app/) on {date.today().isoformat()}._
_Generated by `explorer/archive-results.py`; re-export to refresh this snapshot._

"""


def write_study(path: str, study_id: str, df: pd.DataFrame, pg_major: str | None, nav_order: int) -> None:
    body = study_frontmatter(study_id, pg_major, nav_order) + "\n" + dataframe_to_markdown(df) + "\n"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"Wrote {path} ({len(df)} rows)")


def write_index(output_dir: str, pg_major: str | None, study_files: list[tuple[str, str]]) -> None:
    title = f"PostgreSQL {pg_major}" if pg_major else "Results summary"
    if pg_major:
        permalink = f"/results-summary/pg{pg_major}/"
        parent = "Results summary"
        intro = f"Published benchmark studies run on PostgreSQL {pg_major}."
    else:
        permalink = "/results-summary/"
        parent = None
        intro = "Static archive of published pgbent benchmark studies (replacing the live Streamlit explorer)."

    front = f"""---
layout: home
title: {title}
permalink: {permalink}
"""
    if parent:
        front += f"parent: {parent}\n"
    if pg_major:
        front += "nav_order: 1\n"
    else:
        front += "nav_order: 6\nhas_children: true\n"
    front += "---\n\n"
    front += f"# {title}\n\n{intro}\n\n"

    if pg_major:
        front += "## Studies\n\n"
        for study_id, filename in study_files:
            meta = STUDIES[study_id]
            front += f"- [{meta['title']}]({{{{ '/results-summary/pg{pg_major}/{study_id}/' | relative_url }}}}) — {meta['description']}\n"
    else:
        front += "## By PostgreSQL version\n\n"
        front += "- [PostgreSQL 18]({{ '/results-summary/pg18/' | relative_url }}) — OSM and pgbench studies on PG 18\n\n"
        front += "## Regenerating\n\n"
        front += "```bash\npython3 explorer/archive-results.py --pg 18\n```\n\n"
        front += "Requires read access to the published `submission` view in the results database.\n"

    index_path = os.path.join(output_dir, "index.md")
    with open(index_path, "w", encoding="utf-8") as f:
        f.write(front)
    print(f"Wrote {index_path}")


def main() -> int:
    args = parse_args()

    if args.list_studies:
        for sid, meta in STUDIES.items():
            print(f"{sid}\t{meta['title']}")
        return 0

    pg_major = args.pg
    if args.output:
        output_dir = args.output
    elif pg_major:
        output_dir = os.path.join("docs", "results-summary", f"pg{pg_major}")
    else:
        output_dir = os.path.join("docs", "results-summary")

    study_ids = list(STUDIES.keys()) if args.study == "all" else [args.study]
    for sid in study_ids:
        if sid not in STUDIES:
            print(f"Unknown study: {sid}", file=sys.stderr)
            return 1

    try:
        conn = connect(args.conn)
    except Exception as e:
        print(f"Database connection failed: {e}", file=sys.stderr)
        print("Set RESULTS_CONN or pass --conn to point at the published results database.", file=sys.stderr)
        return 1

    written: list[tuple[str, str]] = []
    try:
        for nav_order, study_id in enumerate(study_ids, start=1):
            sql = study_sql(study_id, pg_major)
            df = pd.read_sql_query(sql, conn)
            out_path = os.path.join(output_dir, f"{study_id}.md")
            write_study(out_path, study_id, df, pg_major, nav_order)
            written.append((study_id, f"{study_id}.md"))
        write_index(output_dir, pg_major, written)
    finally:
        conn.close()

    if pg_major:
        root_dir = os.path.join("docs", "results-summary")
        root_index = os.path.join(root_dir, "index.md")
        if not os.path.exists(root_index):
            os.makedirs(root_dir, exist_ok=True)
            write_index(root_dir, None, [])

    return 0


if __name__ == "__main__":
    sys.exit(main())
